// Service Worker simples para suporte a PWA e cache de recursos estaticos essenciais
const CACHE_NAME = 'acessilia-v2';
const STATIC_ASSETS = [
  '/public/css/reset.css',
  '/public/css/variables.css',
  '/public/css/components.css',
  '/public/css/layout.css',
  '/public/js/a11y-helpers.js',
  '/public/manifest.json'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(STATIC_ASSETS).catch(() => {});
    })
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(
        keys.map((key) => {
          if (key !== CACHE_NAME) return caches.delete(key);
        })
      );
    })
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);

  // Cache first para assets estaticos de /public/ (compatível com ou sem /gestor)
  if (url.pathname.indexOf('public') !== -1) {
    event.respondWith(
      caches.match(event.request).then((cached) => {
        return cached || fetch(event.request).then((response) => {
          if (response && response.status === 200) {
            const clone = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
          }
          return response;
        });
      })
    );
  }
});
